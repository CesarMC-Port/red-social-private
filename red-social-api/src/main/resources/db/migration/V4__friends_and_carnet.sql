-- Carnet / cédula universitaria (opcional; se valida el formato en el API).
ALTER TABLE users ADD COLUMN carnet varchar(20);

-- Relación N---M Usuarios (tabla intermedia de amistad con estado).
CREATE TABLE friendships (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id  bigint NOT NULL,
    addressee_id  bigint NOT NULL,
    status        varchar(20) NOT NULL,
    created_at    timestamp(6) with time zone NOT NULL,
    updated_at    timestamp(6) with time zone,
    CONSTRAINT uk_friendship_pair UNIQUE (requester_id, addressee_id),
    CONSTRAINT ck_friendship_distinct CHECK (requester_id <> addressee_id),
    CONSTRAINT fk_friendship_requester FOREIGN KEY (requester_id) REFERENCES users (id),
    CONSTRAINT fk_friendship_addressee FOREIGN KEY (addressee_id) REFERENCES users (id)
);
CREATE INDEX idx_friendships_requester ON friendships (requester_id, status);
CREATE INDEX idx_friendships_addressee ON friendships (addressee_id, status);

-- ============================================================
-- V2 — Módulo "Preparadurías" (integración PrepaUnet).
-- Perfil académico en users + catálogo de materias + conexiones + reseñas.
-- Portable PostgreSQL 16 + H2 2.x (MODE=PostgreSQL).
-- ============================================================

-- Tipos de notificación nuevos (CONNECTION, REVIEW): liberar el CHECK legado de
-- notifications.type que restringía los valores en despliegues previos.
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_type_check;

-- Perfil académico (esencial) sobre users
ALTER TABLE users ADD COLUMN career              varchar(120);
ALTER TABLE users ADD COLUMN subject_of_interest varchar(120);
ALTER TABLE users ADD COLUMN tutor_type          varchar(20);

-- Catálogo de materias
CREATE TABLE subjects (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(120) NOT NULL,
    CONSTRAINT uk_subjects_name UNIQUE (name)
);

-- Materias que enseña un preparador, con precio por hora
CREATE TABLE tutor_subjects (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id        bigint NOT NULL,
    subject_id      bigint NOT NULL,
    price_per_hour  numeric(14,2) NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_tutor_subject UNIQUE (tutor_id, subject_id),
    CONSTRAINT fk_tutor_subject_tutor FOREIGN KEY (tutor_id) REFERENCES users (id),
    CONSTRAINT fk_tutor_subject_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
);
CREATE INDEX idx_tutor_subjects_subject ON tutor_subjects (subject_id);

-- Solicitud de conexión estudiante -> preparador
CREATE TABLE connections (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   bigint NOT NULL,
    tutor_id     bigint NOT NULL,
    status       varchar(20) NOT NULL,
    review_code  varchar(12) NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    accepted_at  timestamp(6) with time zone,
    CONSTRAINT uk_connection_pair UNIQUE (student_id, tutor_id),
    CONSTRAINT uk_connection_review_code UNIQUE (review_code),
    CONSTRAINT ck_connection_distinct CHECK (student_id <> tutor_id),
    CONSTRAINT fk_connection_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_connection_tutor FOREIGN KEY (tutor_id) REFERENCES users (id)
);
CREATE INDEX idx_connections_tutor ON connections (tutor_id, status);
CREATE INDEX idx_connections_student ON connections (student_id, status);

-- Reseña del estudiante sobre una conexión aceptada
CREATE TABLE reviews (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id  bigint NOT NULL,
    student_id     bigint NOT NULL,
    tutor_id       bigint NOT NULL,
    rating         integer NOT NULL,
    comment_text   varchar(1000),
    created_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_review_connection UNIQUE (connection_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_review_connection FOREIGN KEY (connection_id) REFERENCES connections (id),
    CONSTRAINT fk_review_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_review_tutor FOREIGN KEY (tutor_id) REFERENCES users (id)
);
CREATE INDEX idx_reviews_tutor ON reviews (tutor_id);

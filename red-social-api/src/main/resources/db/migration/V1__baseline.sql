-- ============================================================
-- V1 — Baseline del esquema RED-SOCIAL existente.
-- Generado desde el dump real de PostgreSQL 16 (red-social-db).
-- Portable PostgreSQL 16 + H2 2.x (MODE=PostgreSQL).
-- En una DB ya desplegada, Flyway la "baselinea" (baseline-version=1)
-- y salta esta migración; en una DB nueva, se aplica completa.
-- ============================================================

CREATE TABLE users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(50)  NOT NULL,
    email          varchar(150) NOT NULL,
    password       varchar(255) NOT NULL,
    display_name   varchar(100),
    bio            varchar(500),
    avatar_url     varchar(500),
    cover_url      varchar(500),
    role           varchar(20)  NOT NULL,
    enabled        boolean      NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE posts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     text NOT NULL,
    media_url   varchar(500),
    media_type  varchar(16),
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone,
    author_id   bigint NOT NULL,
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE comments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     text NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    author_id   bigint NOT NULL,
    post_id     bigint NOT NULL,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id)
);

CREATE TABLE post_likes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) with time zone NOT NULL,
    post_id     bigint NOT NULL,
    user_id     bigint NOT NULL,
    CONSTRAINT uk_post_likes UNIQUE (post_id, user_id),
    CONSTRAINT fk_post_likes_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_post_likes_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE follows (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) with time zone NOT NULL,
    follower_id   bigint NOT NULL,
    following_id  bigint NOT NULL,
    CONSTRAINT uk_follows_pair UNIQUE (follower_id, following_id),
    CONSTRAINT fk_follows_follower FOREIGN KEY (follower_id) REFERENCES users (id),
    CONSTRAINT fk_follows_following FOREIGN KEY (following_id) REFERENCES users (id)
);

CREATE TABLE conversations (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamp(6) with time zone NOT NULL,
    last_message_at  timestamp(6) with time zone
);

CREATE TABLE conversation_participants (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  bigint NOT NULL,
    user_id          bigint NOT NULL,
    CONSTRAINT uk_conversation_participant UNIQUE (conversation_id, user_id),
    CONSTRAINT fk_conv_part_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_conv_part_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE messages (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content          text NOT NULL,
    created_at       timestamp(6) with time zone NOT NULL,
    read_at          timestamp(6) with time zone,
    conversation_id  bigint NOT NULL,
    sender_id        bigint NOT NULL,
    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);

CREATE TABLE projects (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6) with time zone NOT NULL,
    updated_at     timestamp(6) with time zone,
    description    text NOT NULL,
    event_date     timestamp(6) without time zone,
    kind           varchar(20) NOT NULL,
    location       varchar(200),
    raised_amount  numeric(14,2),
    status         varchar(20),
    target_amount  numeric(14,2),
    title          varchar(160) NOT NULL,
    creator_id     bigint NOT NULL,
    CONSTRAINT fk_projects_creator FOREIGN KEY (creator_id) REFERENCES users (id)
);

CREATE TABLE donations (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount      numeric(14,2) NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    donor_id    bigint NOT NULL,
    project_id  bigint NOT NULL,
    CONSTRAINT fk_donations_donor FOREIGN KEY (donor_id) REFERENCES users (id),
    CONSTRAINT fk_donations_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE notifications (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) with time zone NOT NULL,
    read          boolean NOT NULL,
    target_id     bigint,
    text          varchar(400) NOT NULL,
    type          varchar(20) NOT NULL,
    actor_id      bigint NOT NULL,
    recipient_id  bigint NOT NULL,
    CONSTRAINT fk_notifications_actor FOREIGN KEY (actor_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES users (id)
);
